func activityOverviewResponse(value *operationrecord.Overview) protocol.ActivityOverview {
	result := protocol.ActivityOverview{
		ConnectionDurationIsLowerBound: value.ConnectionDurationIsLowerBound,
		MetricVersion:                  value.MetricVersion,
		AsOf:                           value.AsOf,
		Start:                          value.Start,
		End:                            value.End,
		Timezone:                       value.Timezone,
		Coverage:                       value.Coverage,
		Volume:                         value.Volume,
		Targets:                        value.Targets,
		ResultEvents:                   value.ResultEvents,
		TargetResultEvents:             value.TargetResultEvents,
		CarryOver:                      value.CarryOver,
		ConnectionDurationMs:           value.ConnectionDurationMs,
		Servers:                        value.Servers,
		Timeline:                       value.Timeline,
		Total:                          value.Total,
		Page:                           value.Page,
		PageSize:                       value.PageSize,
		Records:                        make([]protocol.ActivityWorkSummary, 0, len(value.Records)),
	}
	for _, record := range value.Records {
		result.Records = append(result.Records, protocol.ActivityWorkSummary{
			WorkID:                   record.WorkID,
			ParentWorkID:             record.ParentWorkID,
			WorkStartedAt:            record.WorkStartedAt,
			Attempt:                  record.Attempt,
			EstablishedAt:            record.EstablishedAt,
			ConnectionUncertainUntil: record.ConnectionUncertainUntil,
			Actor:                    record.Actor,
			ID:                       record.ID,
			Username:                 record.Username,
			Type:                     record.Type,
			Category:                 record.Category,
			Action:                   record.Action,
			Status:                   record.Status,
			ServerID:                 record.ServerID,
			ServerName:               record.ServerName,
			Title:                    record.Title,
			Resource:                 record.Resource,
			Source:                   record.Source,
			IP:                       record.IP,
			StartedAt:                record.StartedAt,
			FinishedAt:               record.FinishedAt,
			DurationMs:               record.DurationMs,
			Progress:                 record.Progress,
			TotalCount:               record.TotalCount,
			SuccessCount:             record.SuccessCount,
			FailureCount:             record.FailureCount,
			BytesTotal:               record.BytesTotal,
			BytesProcessed:           record.BytesProcessed,
			BytesCompleted:           record.BytesCompleted,
			SpeedBps:                 record.SpeedBps,
			ErrorMessage:             record.ErrorMessage,
			SourceTable:              record.SourceTable,
			SourceID:                 record.SourceID,
			CreatedAt:                record.CreatedAt,
			UpdatedAt:                record.UpdatedAt,
			EverFailed:               record.EverFailed, Recovered: record.Recovered, ObservedAttempts: record.ObservedAttempts, Resources: record.Resources})
	}
	return result
}
