import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE || '/tmp/easyssh-browser-check/node_modules/playwright/index.mjs'))
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/root/.cache/ms-playwright/chromium-1208/chrome-linux64/chrome', args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1200, height: 900 } })
const report = { checks: [], errors: [], scope: 'Local fixture: actual Dockview, React portals and Pragmatic adapters; no SSH/network transfers' }
page.on('pageerror', error => report.errors.push(error.message))
const check = async (name, fn) => { await fn(); report.checks.push({ name, passed: true }); console.log(name) }
const state = fn => page.evaluate(fn)
// Keep argument passing explicit; the bridge accepts source-workspace / target-ordinary order.
async function join(source, target, side = 'right') {
  await page.evaluate(({source,target,side}) => window.workspaceAudit.work.handleSplitPaneDropToTab(target, source, side), {source,target,side})
  await page.waitForFunction(() => window.workspaceAudit.work.hasWorkspace)
}
try {
  await page.goto((process.env.EASYSSH_BASE_URL || 'http://localhost:3000') + '/test/fixtures/workspace-libraries.html')
  await page.waitForFunction(() => window.workspaceAudit?.work.dockview.api)
  await check('page and system loaders use distinct styles', async () => {
    assert.equal(await page.locator('#page-loader .lucide-loader-circle, #page-loader .lucide-loader2').count(), 1)
    assert.match(await page.locator('#page-loader').innerText(), /加载服务器列表/)
    assert.equal(await page.locator('#system-loader .lucide').count(), 0)
  })
  await page.locator('[data-draft=b]').fill('unsaved workspace draft')
  const draft = await page.locator('[data-draft=b]').elementHandle()
  const mounts = await state(() => ({...window.workspaceAudit.mounts}))
  await check('merge creates two panels without remounting sessions', async () => {
    await join('a','b')
    await page.locator('[data-dockview-session-id=a]').waitFor()
    await page.locator('[data-dockview-session-id=b]').waitFor()
    assert.equal(await state(() => window.workspaceAudit.work.dockview.api.panels.length), 2)
    assert.equal(await page.locator('[data-draft=b]').inputValue(), 'unsaved workspace draft')
    assert.deepEqual(await state(() => window.workspaceAudit.mounts), mounts)
    assert.ok(await draft.evaluate(el => el.isConnected))
    const bounds = await page.locator('[data-draft=b]').boundingBox(); assert.ok(bounds.width > 200)
  })
  await check('pane toolbar follows its session and close remains last', async () => {
    const group = page.locator('[data-workspace-pane-session-id=b]')
    const actions = group.locator('.dv-right-actions-container')
    await actions.locator('[data-toolbar=b]').click()
    assert.deepEqual(await state(() => window.workspaceAudit.operations.pop()), { kind: 'toolbar', id: 'b' })
    const close = actions.getByRole('button', { name: 'ariaCloseSplitPaneSession' })
    assert.equal(await close.count(), 1)
    assert.equal(await group.getByRole('button', { name: 'ariaCloseSplitPaneSession' }).count(), 1)
    const closeRect = await close.boundingBox(), groupRect = await group.boundingBox()
    assert.ok(Math.abs(groupRect.x + groupRect.width - closeRect.x - closeRect.width) < 10)
    assert.equal(await actions.locator('[data-nested-toolbar]').count(), 0)
    assert.equal(await page.locator('[data-split-session-id=b] [data-nested-toolbar=b]').count(), 1)
    assert.equal(await page.locator('[data-workspace-pane-session-id=a]').getByRole('button', { name: 'ariaCloseSplitPaneSession' }).count(), 0)
  })
  await check('merge preview and dashed border include the pane header', async () => {
    await state(() => window.workspaceAudit.setPreview('b'))
    const group = page.locator('[data-workspace-pane-session-id=b]')
    const overlay = group.locator(':scope > .pointer-events-none.absolute.inset-0')
    await overlay.waitFor()
    const outer = await group.boundingBox(), inner = await overlay.boundingBox()
    for (const key of ['x', 'y', 'width', 'height']) assert.ok(Math.abs(outer[key] - inner[key]) < 1)
    assert.equal(await group.evaluate(el => getComputedStyle(el, '::after').borderTopStyle), 'dashed')
    assert.equal(await overlay.locator(':scope > div').evaluate(el => getComputedStyle(el).borderTopStyle), 'dashed')
    await state(() => window.workspaceAudit.setPreview(null))
  })
  await check('workspace switching preserves content and draft', async () => {
    await state(() => window.workspaceAudit.work.handleChangeActiveSession('home'))
    await state(() => window.workspaceAudit.work.handleChangeActiveSession('workspace'))
    assert.ok(await draft.evaluate(el => el.isConnected))
    assert.equal(await page.locator('[data-draft=b]').inputValue(), 'unsaved workspace draft')
    assert.deepEqual(await state(() => window.workspaceAudit.mounts), mounts)
  })
  await check('Pragmatic handles same-session moves once', async () => {
    await page.locator('[data-files=b] [data-file="file.txt"]').dragTo(page.locator('[data-files=b] [data-file=folder]'))
    assert.deepEqual(await state(() => window.workspaceAudit.operations), [{kind:'move',id:'b',oldName:'file.txt',newName:'folder/file.txt'}])
  })
  await check('Pragmatic handles cross-session drops once', async () => {
    await page.locator('[data-files=b] [data-file="file.txt"]').dragTo(page.locator('[data-files=a] [data-file=folder]'))
    const ops = await state(() => window.workspaceAudit.operations)
    assert.equal(ops.length,2); assert.equal(ops[1].kind,'transfer'); assert.equal(ops[1].target,'a'); assert.equal(ops[1].data.filePath,'/tmp/file.txt')
  })
  await check('external upload still works after file browser remount, once', async () => {
    await page.locator('[data-toggle-files=b]').click(); await page.locator('[data-toggle-files=b]').click()
    const transfer = await page.evaluateHandle(() => { const d = new DataTransfer(); d.items.add(new File(['data'],'local.txt')); return d })
    const target = page.locator('[data-files=b]')
    await target.dispatchEvent('dragenter', { dataTransfer: transfer })
    await target.dispatchEvent('dragover', { dataTransfer: transfer })
    await target.dispatchEvent('drop', { dataTransfer: transfer })
    await page.waitForFunction(() => window.workspaceAudit.operations.length === 3)
    assert.deepEqual((await state(() => window.workspaceAudit.operations))[2], {kind:'upload',id:'b',names:['local.txt']})
  })
  await check('nested third panel and resize are stored by Dockview', async () => {
    await join('c','b','bottom')
    assert.equal(await state(() => window.workspaceAudit.work.dockview.api.panels.length),3)
    const sash = page.locator('.dv-sash:visible').first()
    const rect = await sash.boundingBox()
    const before = await state(() => JSON.stringify(window.workspaceAudit.work.splitLayout.grid))
    await page.mouse.move(rect.x+rect.width/2, rect.y+rect.height/2); await page.mouse.down(); await page.mouse.move(rect.x+rect.width/2+70, rect.y+rect.height/2+60,{steps:8}); await page.mouse.up()
    await page.waitForFunction(before => JSON.stringify(window.workspaceAudit.work.splitLayout.grid) !== before, before)
  })
  await check('Dockview native docking preserves content identity', async () => {
    await page.locator('[data-dockview-session-id=c]').dragTo(page.locator('[data-dockview-session-id=b]'))
    await page.waitForFunction(() => window.workspaceAudit.work.dockview.api.getPanel('c').group === window.workspaceAudit.work.dockview.api.getPanel('b').group)
    assert.ok(await draft.evaluate(el => el.isConnected))
    assert.deepEqual(await state(() => window.workspaceAudit.mounts), mounts)
    assert.equal(await page.locator('[data-split-session-id][aria-hidden=false]').count(),2)
  })
  await check('file drop onto grouped hidden session tab reaches that session once', async () => {
    const before = await state(() => window.workspaceAudit.operations.length)
    await page.locator('[data-files=a] [data-file="file.txt"]').dragTo(page.locator('[data-dockview-session-id=b]'))
    const ops = await state(() => window.workspaceAudit.operations)
    assert.equal(ops.length,before+1); assert.equal(ops.at(-1).kind,'transfer'); assert.equal(ops.at(-1).target,'b')
  })
  await check('activating grouped hidden session restores correct visibility', async () => {
    await state(() => window.workspaceAudit.setActive('b'))
    await page.waitForFunction(() => window.workspaceAudit.work.visibleSessionIdSet.has('b'))
    assert.equal(await page.locator('[data-draft=b]').inputValue(),'unsaved workspace draft')
  })
  await check('grouped tabs switch to the active session toolbar', async () => {
    const group = page.locator('[data-workspace-pane-session-id=b]')
    await group.locator('.dv-right-actions-container [data-toolbar=b]').waitFor()
    assert.equal(await group.locator('.dv-right-actions-container [data-toolbar=c]').count(), 0)
    await state(() => window.workspaceAudit.setActive('c'))
    const active = page.locator('[data-workspace-pane-session-id=c]')
    await active.locator('[data-toolbar=c]').waitFor()
    await state(() => window.workspaceAudit.setActive('b'))
    await group.locator('[data-toolbar=b]').waitFor()
    assert.ok(await draft.evaluate(el => el.isConnected))
  })
  await check('fixed tab resists keyboard close', async () => {
    const tab = page.locator('.dv-tab').filter({has:page.locator('[data-dockview-session-id=a]')})
    await tab.focus(); await page.keyboard.press('Delete')
    assert.equal(await state(() => window.workspaceAudit.work.dockview.api.panels.length),3)
    assert.equal(await tab.getByRole('button').count(),1)
  })
  await check('detach restores ordinary tab without replacing draft', async () => {
    await page.locator('[data-dockview-session-id=b]').getByRole('button',{name:'detachWorkspaceSession'}).click()
    await page.waitForFunction(() => !window.workspaceAudit.work.workspaceSessionIdSet.has('b'))
    assert.ok(await draft.evaluate(el => el.isConnected))
    assert.equal(await page.locator('[data-draft=b]').inputValue(),'unsaved workspace draft')
    assert.deepEqual(await state(() => window.workspaceAudit.mounts),mounts)
  })
  await check('keyboard close uses application close and collapses singleton', async () => {
    await state(() => window.workspaceAudit.setActive('c'))
    const tab = page.locator('.dv-tab').filter({has:page.locator('[data-dockview-session-id=c]')})
    await tab.focus(); await page.keyboard.press('Delete')
    await page.waitForFunction(() => !window.workspaceAudit.work.hasWorkspace)
    assert.equal(await state(() => window.workspaceAudit.sessions.some(s=>s.id==='c')),false)
    assert.equal(await state(() => window.workspaceAudit.work.dockview.api.panels.length),0)
  })
  await check('serialized layout restores across route remount', async () => {
    await join('a','b')
    await page.locator('#toggle').click(); await page.locator('#toggle').click()
    await page.waitForFunction(() => window.workspaceAudit.work.dockview.api?.panels.length === 2)
    await page.locator('[data-dockview-session-id=b]').waitFor()
    await page.waitForFunction(() => document.querySelector('[data-draft=b]').getBoundingClientRect().width > 200)
  })
  await check('Dockview native header can return to ordinary plus target', async () => {
    await page.locator('[data-dockview-session-id=b]').dragTo(page.locator('#ordinary-plus'))
    await page.waitForFunction(() => !window.workspaceAudit.work.hasWorkspace)
    assert.equal(await state(() => window.workspaceAudit.active),'b')
    assert.equal(await state(() => window.workspaceAudit.sessions.length),3)
  })
  await check('rightmost close button closes its own session and collapses the workspace', async () => {
    await join('a', 'b')
    await page.locator('[data-workspace-pane-session-id=b]').getByRole('button', { name: 'ariaCloseSplitPaneSession' }).click()
    await page.waitForFunction(() => !window.workspaceAudit.work.hasWorkspace)
    assert.equal(await state(() => window.workspaceAudit.sessions.some(s => s.id === 'b')), false)
    assert.equal(await state(() => window.workspaceAudit.sessions.some(s => s.id === 'a')), true)
  })
  assert.deepEqual(report.errors,[])
} catch(error) { report.fatal = error.stack; console.error(error); process.exitCode=1 }
finally { await writeFile(process.env.AUDIT_REPORT || '/tmp/easyssh-workspace-libraries.json',JSON.stringify(report,null,2)); await browser.close() }
